import assert from 'node:assert/strict';
import { mkdtemp, mkdir, readFile, writeFile, copyFile, rm } from 'node:fs/promises';
import { resolve, join, sep } from 'node:path';
import { tmpdir } from 'node:os';
import { pathToFileURL } from 'node:url';
import { createHash } from 'node:crypto';

const output = resolve('output/phase9-cross-application-2026-10-11');
const report = JSON.parse(await readFile(join(output, 'mutation-gps-focused.json'), 'utf8'));
const sourcePath = 'tools/phase9-native/synthetic-location-stage.mjs';
const original = await readFile(sourcePath, 'utf8');
const entry = report.files[sourcePath];
assert.equal(entry.source, original, 'Review must use the exact tested source');
const survivors = entry.mutants.filter(value => value.status === 'Survived');
assert.equal(survivors.length, 2);
const temporary = await mkdtemp(join(tmpdir(), 'rcs-phase9-equivalence-'));
const results = [];
try {
  for (const file of ['maps-test.mjs', 'stage.mjs', 'synthetic-location-core.mjs']) await copyFile('tools/phase9-native/' + file, join(temporary, file));
  const fixture = async name => {
    const app = join(temporary, name), repository = join(temporary, 'repository');
    await mkdir(app); await mkdir(repository, { recursive: true });
    await writeFile(join(app, 'app.json'), JSON.stringify({ expo: { name: '\u0938\u093f\u0902\u0925\u0947\u091f\u093f\u0915', android: { package: 'com.rcstravels.driver.phase9' } } }));
    await writeFile(join(app, 'metro.config.js'), 'module.exports={resolver:{}};\n// \u0905\u0915 UTF8 fixture\n');
    return { app, repository };
  };
  await writeFile(join(temporary, 'baseline.mjs'), original);
  const baseline = await import(pathToFileURL(join(temporary, 'baseline.mjs')).href);
  const base = await fixture('baseline-app');
  const baseMetadata = await baseline.stageSyntheticLocation(base.app, base.repository);
  const generated = ['phase9-location.js', 'phase9-location-core.mjs', 'metro.config.js'];
  for (const mutant of survivors) {
    assert.equal(mutant.mutatorName, 'StringLiteral'); assert.equal(mutant.replacement, '""');
    const lines = original.split('\n'), { start, end } = mutant.location;
    assert.equal(start.line, end.line);
    const line = lines[start.line - 1];
    assert.equal(line.slice(start.column - 1, end.column - 1), "'utf8'");
    lines[start.line - 1] = line.slice(0, start.column - 1) + mutant.replacement + line.slice(end.column - 1);
    const variant = join(temporary, 'variant-' + mutant.id + '.mjs');
    await writeFile(variant, lines.join('\n'));
    const module = await import(pathToFileURL(variant).href);
    const context = await fixture('variant-app-' + mutant.id);
    assert.deepEqual(await module.stageSyntheticLocation(context.app, context.repository), baseMetadata);
    for (const file of generated) assert.deepEqual(await readFile(join(context.app, file)), await readFile(join(base.app, file)));
    results.push({ file: sourcePath, location: mutant.location, mutatorName: mutant.mutatorName, replacement: mutant.replacement,
      sourceSha256: createHash('sha256').update(original).digest('hex'), status: 'REVIEWED_EQUIVALENT',
      witness: 'Real filesystem UTF-8 multibyte inputs produce identical metadata and generated bytes',
      reason: 'Empty fs encoding returns Buffer; JSON.parse and string concatenation coerce it with the identical UTF-8 decoding. The marker search is ASCII.' });
  }
  await writeFile(join(output, 'reviewed-utf8-equivalences.json'), JSON.stringify({ schema: 'phase9-reviewed-equivalences-v1', results }, null, 2));
  console.log('Reviewed UTF8 equivalences: ' + results.length + '/' + survivors.length + ' PASS');
} finally {
  assert.ok(resolve(temporary).startsWith(resolve(tmpdir()) + sep + 'rcs-phase9-equivalence-'));
  await rm(temporary, { recursive: true, force: true });
}
