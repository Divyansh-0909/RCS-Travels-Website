import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { config } from '../handoff/config.mjs';
import { atomicJson, readJson } from '../handoff/core.mjs';
const require = createRequire(path.join(config.root, 'frontend/package.json'));
const { chromium, expect } = require('@playwright/test');
const run = readJson(path.join(config.runtime, 'state.json')).run, out = path.join(run.directory, 'artifacts');
const proof = { phase: 'P04', at: new Date().toISOString(), checks: [], screenshots: [] };
const browser = await chromium.launch();
try {
  const context = await browser.newContext({ reducedMotion: 'reduce' });
  await context.route('**/*', route => ['127.0.0.1', 'localhost'].includes(new URL(route.request().url()).hostname) ? route.continue() : route.abort());
  const page = await context.newPage(), errors = [];
  page.on('pageerror', e => errors.push(e.message));
  for (const viewport of [{ width: 1440, height: 1000 }, { width: 390, height: 844 }]) {
    await page.setViewportSize(viewport);
    await page.goto('http://127.0.0.1:4317/?mode=android&issue=P04-A1');
    const frame = page.frameLocator('#site');
    await expect(page.locator('#site')).toHaveAttribute('src', 'http://127.0.0.1:4317/native');
    await expect(page.locator('#queue button')).toHaveCount(2);
    await expect(page.locator('#screen')).toContainText('P04-A1');
    await expect(page.locator('#decision')).toContainText('Both approved P04 issues are implemented.');
    await expect(page.locator('#measurement')).toContainText('48px');
    await expect(page.locator('#measurement')).toContainText('LIVE · DEVICE');
    await expect(frame.locator('#screen')).toBeVisible({ timeout: 20000 });
    expect(await frame.locator('#screen').evaluate(e => e.naturalWidth)).toBe(1080);
    const first = await frame.locator('#screen').getAttribute('src');
    await expect.poll(() => frame.locator('#screen').getAttribute('src'), { timeout: 15000 }).not.toBe(first);
    await page.locator('[data-issue="P04-A2"]').click();
    await expect(page.locator('#screen')).toContainText('P04-A2');
    await expect(page.locator('#issue')).toContainText('selected=true');
    await expect(page.locator('#decision')).toContainText('P04-A2 is implemented');
    await expect(page.locator('#decision')).not.toContainText('pending');
    await expect(page.locator('#site')).toHaveAttribute('src', 'http://127.0.0.1:4317/native');
    await page.locator('[data-issue="P04-A1"]').click();
    await expect(page.locator('#measurement')).toContainText('LIVE · DEVICE');
    expect(await frame.locator('#screen').evaluate(e => e.getBoundingClientRect().bottom <= innerHeight + 1)).toBe(true);
    expect(await frame.locator('#screen').evaluate(e => e.getBoundingClientRect().top >= 0)).toBe(true);
    expect(await page.locator('.preview').evaluate(e => e.scrollHeight <= e.clientHeight + 1)).toBe(true);
    expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false);
    const filename = `P04-live-viewer-${viewport.width}.png`;
    await page.screenshot({ path: path.join(out, filename), fullPage: true }); proof.screenshots.push(filename);
    proof.checks.push({ viewport, nativeQueue: true, issueLinks: true, real1080pxFrame: true, frameAdvances: true, browserControlsPhone: false, overflow: false });
  }
  const hiddenStatus = async route => route.fulfill({ json: { live: false, status: 'STALE / CAPTURE STOPPED', source: 'DEVICE', ageMs: 16000, package: 'com.rcstravels.driver.phase9', width: 1080, height: 2400 } });
  await context.route('**/api/native/status', hiddenStatus);
  await expect(page.frameLocator('#site').locator('#screen')).toBeHidden({ timeout: 10000 });
  await expect(page.locator('#measurement')).toContainText('ANDROID NOT LIVE');
  await context.unroute('**/api/native/status', hiddenStatus);
  await expect(page.frameLocator('#site').locator('#screen')).toBeVisible({ timeout: 10000 });
  proof.checks.push({ staleSimulation: 'intercepted status only; fixture untouched', staleFrameHidden: true, freshRecovery: true });
  await page.locator('#website').click();
  await expect(page.locator('#queue button')).toHaveCount(5);
  await page.locator('[data-issue="P03-O1"]').click();
  await expect(page.locator('#site')).toHaveAttribute('src', config.previewUrl + '/outstation');
  await expect(page.locator('#measurement')).toContainText('LIVE:', { timeout: 30000 });
  await expect(page.locator('#decision')).toContainText('owner chose to keep');
  await page.locator('[data-issue="P03-H2"]').click();
  await expect(page.locator('#site')).toHaveAttribute('src', config.previewUrl + '/');
  await expect(page.locator('#measurement')).toContainText('LIVE:', { timeout: 30000 });
  await page.locator('#android').click();
  await expect(page.locator('#screen')).toContainText('P04-A1');
  proof.checks.push({ websiteQueue: 'five preserved issues', distinctActualRoutes: true, measuredLiveWebsiteBridge: true, ownerDecisionPreserved: true, androidSelectionPreserved: true });
  expect(errors).toEqual([]); proof.status = 'PASS'; proof.pageErrors = errors;
} finally { await browser.close(); atomicJson(path.join(out, 'P04-viewer-verification.json'), proof); }
console.log(JSON.stringify(proof));
